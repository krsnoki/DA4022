"""Kaggle script kernel: clone the repo, install deps, run one experiment command.

Generated by make_job.py -- edit the values there, not here.
Outputs (results CSV/JSONL, logs, summary) end up in /kaggle/working/outputs,
which Kaggle keeps as the kernel output (download with `kaggle kernels output`).
Caches and checkpoints go to /kaggle/tmp so they do not fill the 20 GB output quota.
"""

import os
import subprocess
import sys

REPO_URL = "__REPO_URL__"
BRANCH = "__BRANCH__"
COMMAND = """__COMMAND__"""
EXTRA_PIP = "__EXTRA_PIP__"


def sh(cmd, **kw):
    print(f"$ {cmd}", flush=True)
    subprocess.run(cmd, shell=True, check=True, **kw)


os.makedirs("/kaggle/tmp", exist_ok=True)
os.environ["HF_HOME"] = "/kaggle/tmp/hf"
os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")

url = REPO_URL
try:  # optional: private fork -> add a Kaggle secret named GITHUB_TOKEN
    from kaggle_secrets import UserSecretsClient

    tok = UserSecretsClient().get_secret("GITHUB_TOKEN")
    if tok:
        url = url.replace("https://", f"https://{tok}@")
except Exception:
    pass

sh("nvidia-smi || true")
sh(f"git clone --depth 1 -b {BRANCH} {url} /kaggle/tmp/repo")
os.chdir("/kaggle/tmp/repo")
sh("git log -1 --oneline")
# torch is preinstalled with CUDA on Kaggle; install the rest
sh(f"{sys.executable} -m pip install -q -r Quantization_and_Pruning/requirements-jacobian-noise.txt {EXTRA_PIP}")
sh(f"{sys.executable} -m pytest -q Quantization_and_Pruning/tests -x")  # fail fast if the env is broken
os.makedirs("/kaggle/working/outputs", exist_ok=True)
env = dict(os.environ, OUT=os.environ.get("OUT", "/kaggle/working/outputs/jacobian_noise"), PYTHON=sys.executable)
sh(COMMAND, env=env)
